#!/usr/bin/env node
import { writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// Static sprites avoid clone initialization races and clone-count limits.
export function columnActors(width) {
  return Array.from({ length: width }, (_, column) => {
    const names = ["y", "end", "color", "r", "g", "b", "max", "min", "delta", "hue", "sat", "extend"]
      .map(name => JSON.stringify(`__pc_${column}_${name}`));
    return `sprite("Column ${column}", { visible: false }, () => {
  onMessage("__pd_render_columns", () => {
    displayRenderColumn(${column}, ${names.join(", ")});
  });
});`;
  }).join("\n\n");
}

export function columnDemo(width, height, scale, modulePath = "../modules/pen-display") {
  return `// Generated by tools/pen-display-columns.mjs. Regenerate to change actor count.
import { displayInit, displayWaitFrame, displaySetRefreshRate } from "${modulePath}/display";
import { displayPresentColumns, displayRenderColumn } from "${modulePath}/columns";
import { displayClear, displayFillRect, displayPixel } from "${modulePath}/framebuffer";
import { rgb, pdState } from "${modulePath}/state";

sprite("Display Controller", { visible: false }, () => {
  onStart(() => {
    displayInit(${width}, ${height}, ${scale}, ${-width * scale / 2}, ${height * scale / 2}, 30);
    setVar("demo_frame", 0);
    forever(() => {
      displayWaitFrame();
      warp(() => {
        displayClear(rgb(8, 12, 24));
        for (let demoBand = 0; demoBand < 8; demoBand++) {
          displayFillRect(demoBand * ${width / 8}, 0, ${width / 8}, ${Math.max(1, Math.floor(height / 3))}, rgb(demoBand * 36, 255 - demoBand * 36, 128));
        }
        displayFillRect(pdState("demo_frame") % ${Math.max(1, width - 5)}, ${Math.floor(height / 2)}, 6, 6, rgb(255, 90, 40));
        displayPixel(pdState("demo_frame") % ${width}, ${height - 1}, rgb(40, 220, 255));
      });
      displayPresentColumns();
      changeVar("demo_frame", 1);
    });
  });
  onKey("49", () => { displaySetRefreshRate(15); });
  onKey("50", () => { displaySetRefreshRate(30); });
  onKey("51", () => { displaySetRefreshRate(60); });
});

${columnActors(width)}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const width = Number(process.argv[2] ?? 32);
  const height = Number(process.argv[3] ?? 20);
  const scale = Number(process.argv[4] ?? 28);
  if (![width, height, scale].every(n => Number.isInteger(n) && n > 0)) {
    throw new Error("Usage: node tools/pen-display-columns.mjs [width height pixelSize [output.ts]]; positive integers required");
  }
  const output = path.resolve(process.argv[5] ?? path.join(root, "samples/pen_display_columns.ts"));
  await mkdir(path.dirname(output), { recursive: true });
  let modulePath = path.relative(path.dirname(output), path.join(root, "modules/pen-display")).replaceAll("\\", "/");
  if (!modulePath.startsWith(".")) modulePath = "./" + modulePath;
  await writeFile(output, columnDemo(width, height, scale, modulePath));
  console.log(`${output}: ${width} column actors + one controller`);
}
