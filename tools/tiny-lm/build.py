"""Compile native KN arithmetic, embed trained weights, localize scratch arrays.

No JS/native-plugin escape hatch: output consists of official math/list/control/
script-variable/pen blocks. Persistent weight lists are copied once into native
temporary lists, so inference does not notify the editor on every scalar write.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT=Path(__file__).resolve().parents[2]

def kernel(model):
    a=model['architecture'];d=a['dim'];ff=a['ff'];vocab=a['vocab']
    assert (d,ff,a['layers'],a['heads'])==(32,128,2,2)
    offsets={};values=[]
    for name,weight in model['weights'].items():
        offsets[name]=len(values);values.extend(weight['values'])
    out=['// Generated by tools/tiny-lm/build.py; arithmetic is native KN blocks.',
        'function v(name:string):number {return getVar(name) as number;}',
        'function item(name:string,index:number):number {return listItem(name,"any",index) as number;}']
    def proc(name,body):out.append(f'defineProc("{name}",[],()=>{{warp(()=>{{\n'+ '\n'.join(body)+'\n});});')
    def norm(name,weight):
        lines=['setVar("ss",0);']
        for i in range(d):lines.append(f'changeVar("ss",v("x{i}")*v("x{i}"));')
        lines.append(f'setVar("inv",1/mathFunc("sqrt",v("ss")/{d}+0.00001));')
        for i in range(d):lines.append(f'setVar("s{i}",v("x{i}")*v("inv")*item("lm_weights",{offsets[weight]+i+1}));')
        # Separate warps keep serialized statement-chain recursion shallow.
        proc(name+' sum',lines[:d+2]);proc(name, [f'callProc("{name} sum");']+lines[d+2:])
    def matvec(name,weight,inputs,outputs,prefix='s',relu=False):
        lines=[f'deleteListItem("{outputs}","all",1);',f'for(let row=0;row<{inputs[1]};row++){{',
            f'setVar("wi",{offsets[weight]+1}+row*{inputs[0]});','setVar("acc",0);']
        for base in range(0,inputs[0],8):
            expr='+'.join(f'item("lm_weights",v("wi")+{i})*v("{prefix}{i}")' for i in range(base,min(base+8,inputs[0])))
            lines.append(f'changeVar("acc",{expr});')
        if relu:lines.append('if(v("acc")<0)setVar("acc",0);')
        lines.extend([f'appendList("{outputs}",v("acc"));','}'])
        proc(name,lines)
    proc('lm embed',[f'setVar("tokenBase",{offsets["token.weight"]}+v("lm_input_token")*32);',
        f'setVar("positionBase",{offsets["position.weight"]}+v("lm_position")*32);']+
        [f'setVar("x{i}",item("lm_weights",v("tokenBase")+{i+1})+item("lm_weights",v("positionBase")+{i+1}));' for i in range(d)])
    for l in range(2):
        p=f'blocks.{l}.'
        norm(f'lm norm {l} attention',p+'n1.weight')
        norm(f'lm norm {l} ff',p+'n2.weight')
        for n in ['q','k','v']:matvec(f'lm {l} {n}',p+n+'.weight',(d,d),'lm_'+n)
        matvec(f'lm {l} o',p+'o.weight',(d,d),'lm_out')
        matvec(f'lm {l} up',p+'up.weight',(d,ff),'lm_ff',relu=True)
        matvec(f'lm {l} down',p+'down.weight',(ff,d),'lm_out',prefix='f')
        lines=[f'setVar("lm_layer",{l});',f'callProc("lm norm {l} attention");']
        lines.extend(f'callProc("lm {l} {n}");' for n in ['q','k','v'])
        lines.extend(['callProc("lm attention");']+
            [f'setVar("s{i}",item("lm_context",{i+1}));' for i in range(d)])
        # This sequence is split because serialized Blockly next chains are nested.
        proc(f'lm block {l} attention',lines)
        proc(f'lm block {l} residual',[f'callProc("lm {l} o");']+
            [f'changeVar("x{i}",item("lm_out",{i+1}));' for i in range(d)]+[f'callProc("lm norm {l} ff");',f'callProc("lm {l} up");'])
        for group in range(4):proc(f'lm ff load {group}',[f'setVar("f{i}",item("lm_ff",{i+1}));' for i in range(group*32,(group+1)*32)]) if l==0 else None
        proc(f'lm block {l} finish',[f'callProc("lm ff load {g}");' for g in range(4)]+[f'callProc("lm {l} down");']+
            [f'changeVar("x{i}",item("lm_out",{i+1}));' for i in range(d)])
    norm('lm norm final','final.weight')
    matvec('lm logits','token.weight',(d,vocab),'lm_logits')
    # Attention dot: head offset and cache row selected by the runtime.
    lines=['setVar("score",0);']
    for base in [0,8]:
        expr='+'.join(f'item("lm_q",v("headBase")+{i+1})*item("lm_keys",v("cacheBase")+{i+1})' for i in range(base,base+8))
        lines.append(f'changeVar("score",{expr});')
    lines.append('setVar("score",v("score")/4);')
    proc('lm attention dot',lines)
    out.append(f'// {len(values)} trained parameters; offsets are zero-based in the exporter.')
    return '\n'.join(out)+'\n',values,offsets

def blocks(obj):
    if isinstance(obj,dict):
        if 'id' in obj and 'type' in obj:yield obj
        for value in obj.values():yield from blocks(value)
    elif isinstance(obj,list):
        for value in obj:yield from blocks(value)

def localize(project):
    variables=project['variables']['variablesDict'];roots=list(blocks(project))
    # Public controls/telemetry and verification vectors remain inspectable.
    keep={'lm_logits','lm_prompt_tokens','lm_generated_ids','lm_token_ms','lm_top_ids','lm_top_scores'}
    local={key:value['name'] for key,value in variables.items() if value['type']!='list' and not value['name'].startswith('lm_')}
    arrays={key:value['name'] for key,value in variables.items() if value['type']=='list' and value['name'] not in keep}
    for b in roots:
        key=b.get('fields',{}).get('variable')
        if key in local:
            name=local[key]
            if b['type']=='variables_get':b['type']='script_variables_value';b['fields']={'TEXT':name}
            elif b['type'] in ['variables_set','change_variables']:b['fields']['variable']=json.dumps({'name':name,'type':'NEKO_SCRIPT_VARIABLE_TYPE-957f2554-87af'},separators=(',',':'))
            else:raise ValueError(b['type'])
        if b['type'] in ['list_get','pure_list_get'] and b.get('fields',{}).get('list') in arrays:
            name=arrays[b['fields']['list']];b['type']='script_variables_value';b['fields']={'TEXT':'list_'+name};b.pop('is_shadow',None)
    start=next(b for b in roots if b['type']=='on_running_group_activated');tail=start.get('next');last=start
    names=list(local.values())+['list_'+n for n in arrays.values()]
    for batch in range(0,len(names),20):
        group=names[batch:batch+20];bid=f'lm-locals-{batch}'
        declaration={'id':bid,'type':'script_variables','parent_id':last['id'],'shield':False,
            'mutation':'<mutation xmlns="http://www.w3.org/1999/xhtml" items="'+str(len(group))+'">'+''.join(f'<arg name="PARAMS{i}"></arg>' for i in range(len(group)))+'</mutation>',
            'inputs':{f'PARAMS{i}':{'id':f'{bid}-{i}','type':'script_variables_param','parent_id':bid,'fields':{'TEXT':name},'is_output':True,'shield':False} for i,name in enumerate(group)}}
        last['next']=declaration;last=declaration
    for key,name in arrays.items():
        bid='lm-array-'+name
        init={'id':bid,'type':'variables_set','parent_id':last['id'],'shield':False,
            'fields':{'variable':json.dumps({'name':'list_'+name,'type':'NEKO_SCRIPT_VARIABLE_TYPE-957f2554-87af'},separators=(',',':'))},
            'inputs':{'value':{'id':bid+'-value','type':'temporary_list','parent_id':bid,'is_output':True,'shield':False,'mutation':'<mutation xmlns="http://www.w3.org/1999/xhtml" items="0"></mutation>'}}}
        last['next']=init;last=init
        if variables[key]['value']:
            cid=bid+'-copy';copy={'id':cid,'type':'list_copy','parent_id':last['id'],'shield':False,'inputs':{
                'list':{'id':cid+'-src','type':'pure_list_get','parent_id':cid,'fields':{'list':key},'is_output':True,'shield':False},
                'target_list':{'id':cid+'-dst','type':'script_variables_value','parent_id':cid,'fields':{'TEXT':'list_'+name},'is_output':True,'shield':False}}}
            last['next']=copy;last=copy
    if tail:last['next']=tail;tail['parent_id']=last['id']
    for key in list(local)+[key for key in arrays if not variables[key]['value']]:del variables[key]
    return {'scratchScalars':len(local),'scratchLists':len(arrays)}

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--out',type=Path,default=ROOT/'samples/tiny_lm.bcmkn')
    ap.add_argument('--source',type=Path,help='Compile an existing complete TinyLM source without regenerating it')
    ap.add_argument('--banks-from',type=Path,help='Preserve embedded weights/vocabulary from an existing project')
    args=ap.parse_args()
    for original in [args.source,args.banks_from]:
        if original and args.out.resolve()==original.resolve():ap.error('--out must not overwrite an input file')
    model_path=ROOT/'assets/tiny-lm/model.json';model=json.loads(model_path.read_text(encoding='utf8'))
    generated,weights,offsets=kernel(model)
    banks={'lm_weights':weights,'lm_vocabulary':model['vocabulary']}
    if args.banks_from:
        existing=json.loads(args.banks_from.read_text(encoding='utf-8-sig'))
        for name in banks:
            matches=[v for v in existing['variables']['variablesDict'].values() if v['name']==name and v['type']=='list']
            if len(matches)!=1 or len(matches[0]['value'])!=len(banks[name]):ap.error(f'Invalid or missing {name} bank')
            if matches[0]['value']!=banks[name]:ap.error(f'{name} differs from this kernel model; use its matching exporter')
            banks[name]=matches[0]['value']
    if args.source:
        entry=args.source.resolve()
    else:
        source=generated+(ROOT/'modules/tiny-lm/runtime.ts').read_text(encoding='utf8')
        source=source.replace('__VOCAB__',str(model['architecture']['vocab'])).replace('__PARAMETERS__',str(model['parameterCount']))
        entry=ROOT/'samples/tiny_lm.ts';entry.write_text(source,encoding='utf8')
    args.out.parent.mkdir(parents=True,exist_ok=True)
    subprocess.run([str(ROOT/'target/debug/nekoc.exe'),'compile-ts-bcmkn',str(entry),'--template',str(ROOT/'samples/kitten-n-0.27.4.bcmkn'),'--out',str(args.out)],cwd=ROOT,check=True)
    project=json.loads(args.out.read_text(encoding='utf8'))
    for value in project['variables']['variablesDict'].values():
        value['visible']=False
        if value['name'] in banks:value['value']=banks[value['name']]
    info=localize(project)
    data=json.dumps(project,ensure_ascii=False,separators=(',',':')).encode();args.out.write_bytes(data)
    report={'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest(),'modelSha256':hashlib.sha256(model_path.read_bytes()).hexdigest(),
        'parameters':model['parameterCount'],'architecture':model['architecture'],'blocks':sum(1 for _ in blocks(project)),
        'implementation':'official native arithmetic/list/procedure/script-variable blocks; no JS extension or model API',**info}
    if args.source:report['source']=str(entry);report['sourceSha256']=hashlib.sha256(entry.read_bytes()).hexdigest()
    if args.banks_from:report['banksFrom']=str(args.banks_from.resolve());report['banksFromSha256']=hashlib.sha256(args.banks_from.read_bytes()).hexdigest()
    args.out.with_suffix('.build.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf8')
    print(json.dumps(report,indent=2))

if __name__=='__main__':main()
